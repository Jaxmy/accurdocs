def build_inputs():
    """运行输入：单题 1 条/题；组合题按批编号串；末尾附拒答探针。"""
    inputs = []
    for q, txt, _, _ in GROUP1:
        inputs.append({"id": q, "query": txt, "mode": "quote"})
    for bid, items in GROUP2_BATCHES:
        q = "\n".join(f"{i}. {txt}" for i, (_, txt, _, _) in enumerate(items, 1))
        inputs.append({"id": bid, "query": q, "mode": "quote",
                       "qids": [qid for qid, _, _, _ in items]})
    for q, txt, _, _ in GROUP3:
        inputs.append({"id": q, "query": txt, "mode": "analyze"})
    for bid, items in GROUP4_BATCHES:
        q = "\n".join(f"{i}. {txt}" for i, (_, txt, _, _) in enumerate(items, 1))
        inputs.append({"id": bid, "query": q, "mode": "analyze",
                       "qids": [qid for qid, _, _, _ in items]})
    for q, txt, mode in REFUSE_PROBES:
        inputs.append({"id": q, "query": txt, "mode": mode, "qids": [q]})
    return inputs


def input_qids():
    """输入ID → 子题 qid 列表（判分映射）。"""
    m = {}
    for item in build_inputs():
        m[item["id"]] = item.get("qids") or [item["id"]]
    return m
